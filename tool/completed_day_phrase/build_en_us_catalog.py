AUTHOR_TRANSLATIONS = {
    'Refrán popular': 'Popular proverb',
    'Proverbio tradicional': 'Traditional proverb',
    'Proverbio latino': 'Latin proverb',
    'Antonio Machado': 'Antonio Machado',
    'Máxima délfica': 'Delphic maxim',
}


def main() -> None:
    source = json.loads(SOURCE.read_text(encoding='utf-8'))
    phrases = source['phrases']
    if len(phrases) != 300 or len(TEMPLATES) != 300:
        raise SystemExit(f'Expected 300 source/templates, got {len(phrases)}/{len(TEMPLATES)}')

    output_phrases = []
    for source_phrase, template in zip(phrases, TEMPLATES):
        phrase = dict(source_phrase)
        phrase['template'] = template
        phrase['contentVersion'] = 1
        phrase['author'] = AUTHOR_TRANSLATIONS.get(source_phrase['author'])
        output_phrases.append(phrase)

    output = {
        'schemaVersion': 1,
        'catalogVersion': '1',
        'releaseVersion': 1,
        'locale': 'en-US',
        'phrases': output_phrases,
    }
    OUTPUT.write_text(json.dumps(output, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'WROTE {OUTPUT} entries={len(output_phrases)}')


if __name__ == '__main__':
    main()
